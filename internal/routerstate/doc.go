// Package routerstate — персистентное состояние LLM-роутера: счета токенов (инциденты, сервисы по суткам UTC),
// незакрытые резервы, закрепления инцидентов, состояния и счётчики endpoint'ов, активный endpoint, halt.
//
// Состояние хранится как журнал операций (aegisops/router-state/v1): JSONL, только дописывание, fsync после каждой
// строки, один писатель (flock на отдельном файле <path>.lock). Первая строка файла — снимок состояния; когда
// журнал разрастается, снимок переписывается через write-temp + fsync + rename + fsync каталога (компакция).
// Каждая строка — {"seq","sha256","op"}; seq растёт на 1, sha256 — от компактного JSON операции.
//
// Гарантии: Store.Append возвращает nil только после fsync (сначала надёжная запись, потом действие);
// оборванный хвост без перевода строки отбрасывается при открытии (такая запись никогда не подтверждалась);
// любая полная строка с ошибкой — ErrCorrupt, хранилище не открывается (fail-closed); ошибка ввода-вывода
// переводит хранилище в ErrFailed до рестарта процесса.
//
// Тип State и State.Apply общие для всех реализаций (FileStore, MemStore) и для воспроизведения журнала:
// одна и та же операция даёт одно и то же состояние при записи и при чтении.
//
// Ошибки: ErrFailed, ErrCorrupt, ErrLocked, ErrVersion, ErrIdentity, ErrInvalidOp.
