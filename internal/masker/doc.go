// Package masker — маскировщик фрагментов контекста перед отправкой во внешний LLM
// (docs/02-security/data-classes.md §2 «секреты», §3 п. 4–5, §5.1; тот же маскировщик нужен ChatOps-карточкам, T-09).
//
// Детерминированный rule-based маскировщик без LLM и внешних библиотек: regexp (RE2, линейное время),
// контрольные суммы (Luhn, СНИЛС, ИНН, IBAN mod-97), net/netip. Реализует dataclass.Masker. Три прохода по копии значения:
//
//   - правила по именам полей (fields.go): password, token, session_id, phone, inn…; k8s Secret.data; пары {name, value} env-переменных;
//   - строковые детекторы (secrets.go, personal.go) с разрешением пересечений по приоритету
//     секрет > документ/карта > контакт > ФИО;
//   - отчёт: только категории dataclass.CategorySecret и dataclass.CategoryPersonal, Removed — число замен.
//
// Класс фрагмента маскировщик не меняет: любая находка ПДн повышает его до restricted через dataclass.Escalate,
// секрет — вырезается (<SECRET_REMOVED>), класс остаётся. Все сбои (отмена ctx, превышение MaxScanBytes, глубины,
// секрет в ключе объекта) — ошибка, роутер превращает её в masker_failure; поле MaskReport.Failed не используется.
//
// Псевдонимы — "<PERSON_xxxxxxxx>", "<DOC_…>", "<IP_…>" (8 hex от HMAC-SHA256): ключ на инцидент
// HMAC(masterKey, IncidentID), поэтому псевдонимы детерминированы внутри инцидента (§5.1) без хранимой таблицы;
// ключ обязателен, потому что телефоны и ИНН перебираемы. Карты — "<CARD>" без хэша. Таблица соответствий не хранится:
// §5.1 «таблица хранится локально» станет актуальной с локальными моделями.
//
// Что не маскируется (ограничения, поэтому dataclass.ConfidentialExternalAvailable остаётся false):
//   - ФИО — без NER: только кириллица с отчеством («Фамилия Имя Отчество», «Имя Отчество») и «Фамилия И. О.»;
//     латиница и имена без отчества не находятся;
//   - ИНН и паспорт — только с ключевым словом слева (без него число неотличимо от обычного);
//   - национальные номера документов ЕС (кроме IBAN) — отложено;
//   - литералы SQL (§5.1 «$1»): SQL-источники до маскировщика в MVP не доходят по гейту ExternalAllowed — отложено;
//   - числа с плавающей точкой, bool и null не трогаются.
