// Package llmrouter — маршрутизатор запросов к внешней LLM (architecture.md §6.2, data-classes §1.4, §3, §6).
//
// Конвейер Route: фрагменты контекста → гейт по классу источника (неизвестный источник — restricted,
// confidential и ПДн граждан РФ наружу не уходят) → фильтр меток метрик (T-04) → маскировщик → повышение
// класса по его отчёту → сборка input → потолок контекста 64k с отбрасыванием необязательных фрагментов по
// релевантности (T-15) → тело запроса (ZDR, data_collection=deny, без fallback'ов провайдера, T-11) →
// бюджет токенов на инцидент и на сервис в сутки (T-14) → вызов → разбор ответа.
// Подготовка (Prepare) отделена от отправки (Route): Prepare не ходит в сеть и не трогает бюджет, поэтому
// request_sha256 воспроизводится на эталонах eval без сети.
//
// Fail-closed: без маскировщика роутер не создаётся (ErrNoMasker); сбой маскировщика исключает фрагмент
// (restricted); обязательный исключённый фрагмент — запрос не отправляется; сбой записи в аудит останавливает
// роутер (ErrAuditFailed) до ручного Resume; при недоступности обоих endpoint'ов, остановке и исчерпании
// бюджета результат несёт DegradeL1: система работает на уровне не выше L1.
//
// Failover (data-classes §1.4): FailThreshold неудачных попыток подряд переводят primary в down, запросы идут на
// резерв; возврат — после Hysteresis стабильных health-check'ов; инцидент закрепляется за endpoint'ом.
// Каждый переход состояния — событие router-event в той же цепочке аудита (T-12). Состояние и бюджеты
// хранятся в памяти: рестарт их обнуляет (до MVP-B нужен персистентный store).
